export type TKey = keyof typeof DICT;

interface Ctx { lang: Lang; setLang: (l: Lang) => void }
const LangContext = React.createContext<Ctx>({ lang: "mr", setLang: () => {} });

function initial(): Lang {
  try { return localStorage.getItem("lang") === "en" ? "en" : "mr"; } catch { return "mr"; }
}

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = React.useState<Lang>(initial);
  const setLang = React.useCallback((l: Lang) => {
    setLangState(l);
    try { localStorage.setItem("lang", l); } catch { /* storage unavailable */ }
  }, []);
  React.useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  return <LangContext.Provider value={{ lang, setLang }}>{children}</LangContext.Provider>;
}

export function useLang() {
  return React.useContext(LangContext);
}

/** t(key) for UI strings; name(x) picks name_mr / name_en (falling back to Marathi); col(c) for column labels. */
export function useT() {
  const { lang } = useLang();
  return React.useMemo(() => {
    const t = (key: TKey) => DICT[key][lang];
    /** t() with {placeholders} filled in. */
    const tf = (key: TKey, vars: Record<string, string | number>) =>
      DICT[key][lang].replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
    const name = (x: { name_mr: string; name_en?: string } | null | undefined) =>
      !x ? "" : lang === "en" && x.name_en ? x.name_en : x.name_mr;
    const col = (c: { label_mr: string; label_en: string }) => (lang === "en" ? c.label_en : c.label_mr);
    const num = (n: number | null | undefined) =>
      n === null || n === undefined ? "–" : n.toLocaleString(lang === "mr" ? "mr-IN" : "en-IN");
    return { t, tf, name, col, num, lang };
  }, [lang]);
}
